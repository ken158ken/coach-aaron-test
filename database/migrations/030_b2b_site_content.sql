--   hero_title      = '私教變現 系統\n把你的專業，變成穩定的收入'
--   hero_flip_words = ["系統","軍師","陪跑","實戰"]
--
-- 第一行 '私教變現 系統' → 無「|」、有空白 → 套規則 2
--   split(/\s+/)        = ['私教變現', '系統']
--   slice(0, -1).join() = '私教變現'      ← 靜態前綴（永遠留在 <h1>）
--   '系統' 被丟棄，位置交給輪播詞
--
-- 實際輪播畫面（每 2.5 秒換一次）：
--   私教變現 系統          ← 第 1 幀，與原始字面完全相同
--   私教變現 軍師
--   私教變現 陪跑
--   私教變現 實戰
--   把你的專業，變成穩定的收入   ← 第二行原樣輸出，不參與輪播
--
-- ✅ 結論：關鍵字「私教變現」在四幀中都存在，不會被輪播詞吃掉，
--    SSR 首屏的 <h1> 也一定含有該關鍵字（SEO 安全）。
